"""
CS 271P — PA 3D-s : the MCTS framework — PROVIDED, do not edit
============================================================
This runs the Monte-Carlo Tree Search loop and the games. You do NOT edit this file; you edit the
four phase methods in `agent.py`. The driver calls your agent like this, once per iteration, for as
long as its time budget allows:

    1. SELECTION      node = agent.select(node, rng)            # descend the built-out tree
    2. EXPANSION      node = agent.expand(node, game, rng)      # add a child / children at the frontier
    3. SIMULATION     winner = agent.simulate(game, node.state, rng)   # a play-out from there
    4. BACKPROPAGATION agent.backpropagate(node, winner, game)  # push the result up the path

After the time is up, the move played is the **most-visited** child of the root. Your per-move budget
is CPU time (the compute you actually use), so a busy grading machine can't shortchange you — but
sleeping or waiting does not earn you extra samples.

A ready random play-out helper is available: `random_playout(game, state, rng)`.
`Node` fields: `state, parent, move, children (list), untried (list | None), visits, value`.
By convention `value / visits` is the win-rate **from the perspective of the player who moved into
the node** (so a parent maximizing a child's value picks the move best for whoever is choosing).

Two rules the game loop enforces, so you know what a bad move costs you:
  * The move you play must be LEGAL in the current position — i.e. one of `game.actions(state)`.
    Expanding a child on a move you invented forfeits that game.
  * If your agent raises, that game is forfeited too. Both cases lose only the ONE game; the rest
    of the match still runs.
"""

import math
import random
import time

# The per-MOVE budget is measured in CPU TIME (time.process_time), not wall-clock. CPU time counts
# only the compute this process actually consumed, so a noisy / loaded Gradescope container can't
# quietly shrink or inflate an agent's effective budget (that scheduling noise was a real source of
# grade variance), and threads can't buy "free" parallel time — every thread's CPU is charged. It
# does NOT charge separate child processes; a submission that reaches for multiprocessing/subprocess
# is caught by the integrity scan instead. The per-MATCH safety timeout in run_tournament stays on
# wall-clock (SIGALRM) — it must kill a genuinely hung or sleeping agent in real time, and a sleeper
# burns no CPU so CPU time would never trip.
_budget_clock = time.process_time


class Node:
    """One node of the search tree."""
    __slots__ = ("state", "parent", "move", "children", "untried", "visits", "value")

    def __init__(self, state, parent=None, move=None):
        self.state = state
        self.parent = parent
        self.move = move          # the move that led here (from parent)
        self.children = []
        self.untried = None       # moves not yet expanded (None = not initialized yet)
        self.visits = 0
        self.value = 0.0          # summed reward, from the perspective of the player who moved here


def uct(child, c):
    """UCB-for-trees score of `child` from its parent's perspective: exploit + explore.
    (An unvisited child returns +inf so it is tried first.)"""
    if child.visits == 0:
        return float("inf")
    parent_visits = child.parent.visits or 1      # log(0) is undefined; guard a not-yet-visited root
    return child.value / child.visits + c * math.sqrt(math.log(parent_visits) / child.visits)


def random_playout(game, state, rng, ply_cap=40):
    """Play uniformly random moves from `state` until the game ends (or `ply_cap`); return the
    winner ('w' / 'b' / None). A drop-in you may call from `agent.simulate` — or replace with
    something smarter."""
    s, n = state, 0
    while not game.is_terminal(s) and n < ply_cap:
        moves = game.actions(s)
        if not moves:                     # a non-terminal position with no legal move -> stop (draw)
            break
        s = game.result(s, rng.choice(moves))
        n += 1
    return game.winner(s)


# ------------------------------------------------------------------- the driver
def _one_iteration(agent, root, game, rng):
    node = root
    # (1) SELECTION — descend while the node is fully expanded, non-terminal, and has children
    while (not game.is_terminal(node.state)) and node.untried is not None \
            and not node.untried and node.children:
        node = agent.select(node, rng)
    # (2) EXPANSION — if there are still-untried moves here, expand
    if not game.is_terminal(node.state):
        if node.untried is None:
            node.untried = list(game.actions(node.state))
        if node.untried:
            node = agent.expand(node, game, rng)
    # (3) SIMULATION
    winner = agent.simulate(game, node.state, rng)
    # (4) BACKPROPAGATION
    agent.backpropagate(node, winner, game)


def choose_move(agent, game, state, time_budget, rng):
    """Run MCTS from `state` for `time_budget` seconds, then return (best_move, iterations_run).
    The best move is the most-visited child of the root. Returns (None, iters) if the position has
    no legal move (the game loop treats that as game-over)."""
    if not game.actions(state):
        return None, 0
    root = Node(state)
    start = _budget_clock()                          # CPU time, not wall-clock (see module top)
    iters = 0
    while _budget_clock() - start < time_budget:
        _one_iteration(agent, root, game, rng)
        iters += 1
    if not root.children:                       # guarantee at least one expansion
        _one_iteration(agent, root, game, rng)
        iters += 1
    best = max(root.children, key=lambda ch: ch.visits)
    return best.move, iters


# --------------------------------------------------------- playing whole games
class IllegalMove(Exception):
    """An agent returned a move that is not legal in the position it was asked about.

    `choose_move` returns the most-visited child of the root, and those children come only from the
    agent's own `expand`. Nothing else re-checks them, and `game.result` applies whatever it is
    handed — so without this guard an agent could fabricate a move (e.g. teleport its king onto a
    hill square) and win every game. The side that played it forfeits."""

    def __init__(self, side, move):
        super().__init__(f"the {side!r} agent played an illegal move: {move!r}")
        self.side = side
        self.move = move


class AgentError(Exception):
    """An agent raised while choosing a move. Records WHICH side, so the game can be forfeited to
    the opponent instead of taking down the whole match."""

    def __init__(self, side, original):
        super().__init__(f"the {side!r} agent raised {type(original).__name__}: {original}")
        self.side = side
        self.original = original


def play_game(game, agent_white, t_white, agent_black, t_black, start_state, seed=0, ply_cap=60):
    """Play one game from `start_state`; White uses `agent_white` with `t_white` sec/move, Black
    likewise. Returns the winner ('w' / 'b' / None for a draw / ply cap).

    Raises `IllegalMove` / `AgentError` naming the offending side; `play_match` turns either into a
    forfeit of this one game."""
    rng = random.Random(seed)
    s = start_state
    played = 0
    while not game.is_terminal(s) and played < ply_cap:
        legal = game.actions(s)
        if not legal:                               # stuck, non-terminal position -> a draw, no crash
            break
        side = game.to_move(s)
        agent, t = (agent_white, t_white) if side == "w" else (agent_black, t_black)
        try:
            move, _ = choose_move(agent, game, s, t, rng)
        except Exception as e:                      # noqa: BLE001 — re-raised with the side attached
            raise AgentError(side, e) from e
        if move not in legal:                       # the agent picks its children; verify them here
            raise IllegalMove(side, move)
        s = game.result(s, move)
        played += 1
    return game.winner(s)


def _mover_can_force_win(game, s, plies):
    """True if the side to move in `s` can GUARANTEE a win within `plies` plies (its own moves plus
    the opponent's replies). Game-agnostic — uses only winner()/actions()/result()."""
    if plies <= 0 or game.is_terminal(s):
        return False
    me = game.to_move(s)
    for m in game.actions(s):                        # win outright on this move? (1 ply)
        if game.winner(game.result(s, m)) == me:
            return True
    if plies < 3:                                    # no room for a my-move / opp-reply / my-move combo
        return False
    for m in game.actions(s):
        s1 = game.result(s, m)
        if game.is_terminal(s1):
            continue                                 # resolved above (not a win for me)
        replies = game.actions(s1)
        # a forced win iff EVERY opponent reply still lets me force a win in the remaining plies
        if replies and all(_mover_can_force_win(game, game.result(s1, r), plies - 2) for r in replies):
            return True
    return False


def _already_decided(game, s, depth=3):
    """True if `s` is over or its outcome is already forced within `depth` plies.

    The random opening plies can hand one side a forced win before the game really starts; such a
    position measures luck, not skill, so `opening_positions` screens them out. A SHALLOW (1-ply)
    screen was enough for ordinary chess, but King-of-the-Hill has cheap forced wins — a king two
    steps from the hill cannot be stopped (blocking fails; the king captures the blocker and still
    lands) — so a 3-ply forced win is common and must be screened too (measured: ~46% of 4-ply
    openings were pre-decided under a 1-ply screen). We reject if EITHER the side to move can force a
    win within `depth`, OR every move it has lets the opponent force a win within `depth-1` (i.e. it
    is already lost). Game-agnostic: uses only the public game API."""
    if game.is_terminal(s):
        return True
    moves = game.actions(s)
    if not moves:
        return True
    if _mover_can_force_win(game, s, depth):                 # mover has a forced win
        return True
    # mover is forced to lose: no matter what it plays, the opponent can then force a win
    return all(_mover_can_force_win(game, game.result(s, m), depth - 1) for m in moves)


def opening_positions(game, n=6, plies=4, seed=100, max_tries=1200, screen_depth=3):
    """`n` distinct, non-degenerate opening positions.

    `plies` = how many random moves deep each opening is. It may be an INT (every opening that deep)
    or a SEQUENCE of depths, e.g. (4, 8, 12), which are CYCLED across the accepted openings so the set
    spans several game phases.

    Why depth variety: at a single shallow depth the kings have barely moved (random plies mostly push
    pawns), so every opening is structurally the SAME position type -- measured on the all-4-ply set:
    100% had both kings exactly 2 from the hill and 100% had the same side to move, with only the pawn
    shuffle differing. Games from near-identical seeds are correlated, which blunts the averaging that
    playing more games is supposed to buy. Mixed depths yield advanced kings, varied race distances,
    and occasional exposed kings -- broader coverage that is still UNBIASED, because the positions are
    drawn at random rather than hand-picked (curating "interesting" positions would bake in the
    author's view of what matters and can favour one side or one strategy).

    Positions already decided within `screen_depth` plies (see `_already_decided`) or repeating a board
    are skipped, so every opening starts as a real contest. `max_tries` is generous because the deeper
    the draw, the more candidates the screen rejects."""
    depths = (plies,) if isinstance(plies, int) else tuple(plies)
    out, seen, i = [], set(), 0
    while len(out) < n and i < max_tries:
        rng = random.Random(seed + i)
        depth = depths[len(out) % len(depths)]      # cycle depth over the ACCEPTED openings
        i += 1
        s = game.initial()
        for _ in range(depth):
            if game.is_terminal(s):
                break
            s = game.result(s, rng.choice(game.actions(s)))
        if s.board in seen or _already_decided(game, s, depth=screen_depth):
            continue
        seen.add(s.board)
        out.append(s)
    return out


def play_match(game, agent_a, t_a, agent_b, t_b, openings, ply_cap=60, seed_base=0, incidents=None):
    """Play `agent_a` vs `agent_b` over every opening, twice (colors swapped). Returns
    (a_wins, draws, a_losses) from A's point of view.

    An illegal move or a crash forfeits only THAT game — the match plays on, so one bad position
    can't wipe out games the agent had already won. Pass a list as `incidents` to collect the
    (capped) human-readable reasons."""
    aw = dr = al = 0
    for i, op in enumerate(openings):
        for swap in (False, True):
            wp, tw, bp, tb = (agent_b, t_b, agent_a, t_a) if swap else (agent_a, t_a, agent_b, t_b)
            a_is_white = not swap
            try:
                res = play_game(game, wp, tw, bp, tb, op,
                                seed=seed_base + i * 2 + swap, ply_cap=ply_cap)
            except (IllegalMove, AgentError) as e:
                if incidents is not None and len(incidents) < 5:
                    incidents.append(str(e))
                if (e.side == "w") == a_is_white:   # A offended -> A loses this game
                    al += 1
                else:
                    aw += 1
                continue
            if res is None:
                dr += 1
            elif (res == "w") == a_is_white:
                aw += 1
            else:
                al += 1
    return aw, dr, al
